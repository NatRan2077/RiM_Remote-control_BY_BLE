//----------------------------------------------------------------------------//
// service_cmd.h
// Сервисные текстовые команды по USB (виртуальный COM-порт).
//
// Управление списком из 10 паролей (имя + значение BLE passkey).
// Все команды ASCII, завершаются \r\n или \n (необязательно).
//
//   Список:
//     "PWD?"           -> "PWD LIST", далее по строке на слот:
//                         "PWD i=<idx> sel=<0/1> val=<число> name=<имя>"
//                         затем "PWD END"
//   Один слот:
//     "PWD i?"         (i = 0..9) -> "PWD i=<idx> sel=.. val=.. name=.."
//   Задать слот:
//     "PWD i=VAL,NAME" -> "PWD OK" (VAL до 6 цифр, NAME до 11 симв.)
//                         "PWD ERR FORMAT" / "PWD ERR MEM"
//   Выбрать активный:
//     "SEL=i"          -> "SEL OK" / "SEL ERR"
//     "SEL?"           -> "SEL=<idx>"
//
//   Совместимость (одиночный пин = активный слот):
//     "PIN?"           -> "PIN=<val активного>"
//     "PIN=123456"     -> запись в активный слот, "PIN OK"
//
// Обрабатывается в thread_dataRouting ДО HDLC/DLMS-разбора.
//----------------------------------------------------------------------------//
#ifndef SERVICE_CMD_H
#define SERVICE_CMD_H

#include "common_types.h"
#include <stdbool.h>

// true  - буфер распознан и обработан (ответ уже в TX)
// false - не сервисная команда, передать дальше (HDLC/DLMS)
bool ServiceCmd_Process(u8 *buf, u16 len);

#endif // SERVICE_CMD_H
