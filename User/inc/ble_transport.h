//----------------------------------------------------------------------------//
// ble_transport.h
// Транспортный уровень обмена данными по BLE (профиль RDTS).
//
// Модуль владеет буферами приёма/передачи и скрывает их от остального кода.
//
//   Отправка:  ble_transport_send() копирует кадр в TX-буфер и ставит
//              сообщение MSG_REQWEST; физическую передачу выполняет
//              thread_BLE, вызывая ble_transport_process_tx().
//
//   Приём:     стек BLE отдаёт длинные ответы фрагментами (по размеру MTU),
//              ble_transport_on_rx() накапливает их в RX-буфере и ставит
//              MSG_RADIO_ANSWER_OK; потребитель (thread_rim_protocol)
//              читает через ble_transport_rx_data() и после успешного
//              разбора кадра очищает буфер ble_transport_rx_clear().
//----------------------------------------------------------------------------//
#ifndef BLE_TRANSPORT_H
#define BLE_TRANSPORT_H

#include "common_types.h"

//----------------------------------------------------------------------------//
//  Размеры буферов
//----------------------------------------------------------------------------//
#define BLE_TX_BUFF_SIZE 60u // максимальный исходящий кадр
#define BLE_RX_BUFF_SIZE                                                       \
	160u // накопитель входящих фрагментов:
	     // ответ телеметрии ~40 байт приходит
	     // частями по ~20 байт, запас взят
	     // с учётом склейки нескольких ответов

//----------------------------------------------------------------------------//
//  Результат постановки кадра на отправку
//----------------------------------------------------------------------------//
typedef enum {
	BLE_TX_OK = 0,   // кадр принят к передаче
	BLE_TX_ERR_SIZE, // некорректная длина кадра
} bleTxResult_t;

//----------------------------------------------------------------------------//
//  Передача
//----------------------------------------------------------------------------//
bleTxResult_t ble_transport_send(const u8 *data, u8 len);
void ble_transport_process_tx(void);

//----------------------------------------------------------------------------//
//  Приём
//----------------------------------------------------------------------------//
void ble_transport_on_rx(const u8 *data, u16 len);
const u8 *ble_transport_rx_data(u8 *len);
void ble_transport_rx_clear(void);

#endif // BLE_TRANSPORT_H
//----------------------------------------------------------------------------//
